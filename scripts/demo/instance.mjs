#!/usr/bin/env node
import { execFileSync, spawn } from "node:child_process";
import { existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { assertDemo, assertPortsFree, demoEnv } from "./env.mjs";
import { generateMedia } from "./media.mjs";

/**
 * A throwaway branchDAM with synthetic media and a populated version graph.
 *
 *   make demo          # serve it until Ctrl-C, then delete everything
 *   make screenshots   # scripts/demo/capture.mjs drives startDemo()
 *
 * Everything lives in one mkdtemp directory: a config written from scratch
 * (the checkout's config.yaml is never read), the SQLite database, thumbnails
 * and storage roots. The server binds 127.0.0.1 on a port that must be free,
 * has Immich and metadata write-back off, and runs with an environment built
 * from scratch; scripts/demo/env.mjs refuses anything that points elsewhere.
 * Auth is forward mode: the demo browser sends the X-Authentik-* headers.
 */

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const DEMO_PORT = process.env.DEMO_PORT ?? "3975";

/** What the demo browser and scripts send in place of an auth proxy. */
export const DEMO_HEADERS = {
  "X-Authentik-Username": "demo",
  "X-Authentik-Email": "demo@example.com",
  "X-Authentik-Groups": "branchdam-admins",
};

function yaml(cfg) {
  const locations = cfg.storageLocations
    .map((l) => `  - name: ${l.name}\n    rootPath: ${l.rootPath}\n    tier: ${l.tier}\n    readOnly: ${l.readOnly}`)
    .join("\n");
  return `# Generated by scripts/demo/instance.mjs for a throwaway demo instance.
listenAddr: "${cfg.listenAddr}"
logLevel: warn
database:
  path: ${cfg.database.path}
thumbnails:
  enabled: true
  cacheDir: ${cfg.thumbnails.cacheDir}
auth:
  mode: ${cfg.auth.mode}
authz:
  groups:
    - branchdam-admins
immich:
  apiUrl: ""
  apiKey: ""
  libraryId: ""
  exportPath: ${cfg.immich.exportPath}
metadata:
  autoInherit: ${cfg.metadata.autoInherit}
trash:
  retentionDays: 0
storageLocations:
${locations}
`;
}

async function waitFor(check, what, timeoutMs = 120_000) {
  const deadline = Date.now() + timeoutMs;
  let last;
  while (Date.now() < deadline) {
    try {
      if (await check()) return;
    } catch (err) {
      last = err;
    }
    await new Promise((r) => setTimeout(r, 500));
  }
  throw new Error(`timed out waiting for ${what}${last ? `: ${last}` : ""}`);
}

/** Builds web/dist (embedded into the binary) if needed, then the server binary. */
function buildServer(binary) {
  if (!existsSync(path.join(ROOT, "web/dist/index.html"))) {
    console.log("[demo] building the web app...");
    execFileSync("npm", ["--prefix", path.join(ROOT, "web"), "run", "build"], { stdio: "inherit" });
  }
  console.log("[demo] building the server...");
  execFileSync("go", ["build", "-o", binary, "./cmd/branchdam"], { cwd: ROOT, stdio: "inherit" });
}

export async function startDemo({ keep = false, quiet = false } = {}) {
  await assertPortsFree([DEMO_PORT]);
  // A fixed path, so asset paths in captures read cleanly and identically on
  // every run. Created exclusively: a second demo (or a leftover) is refused.
  const demoDir = path.join(tmpdir(), "branchdam-demo");
  try {
    mkdirSync(demoDir);
  } catch (err) {
    if (err.code === "EEXIST")
      throw new Error(`${demoDir} exists: another demo is running, or remove the leftover`);
    throw err;
  }
  const dirs = Object.fromEntries(
    ["home", "tmp", "run", "bin", "data", "archive", "exports", "projects", "staging"].map((d) => [
      d,
      path.join(demoDir, d),
    ]),
  );
  for (const dir of Object.values(dirs)) mkdirSync(dir, { recursive: true });

  const cfg = {
    listenAddr: `127.0.0.1:${DEMO_PORT}`,
    database: { path: path.join(dirs.data, "branchdam.db") },
    thumbnails: { cacheDir: path.join(dirs.data, "thumbs") },
    auth: { mode: "forward" },
    immich: { apiUrl: "", exportPath: path.join(dirs.exports, "immich") },
    metadata: { autoInherit: false },
    storageLocations: [
      { name: "archive", rootPath: dirs.archive, tier: "TIER3_MASTER_ARCHIVE", readOnly: true },
      { name: "staging", rootPath: dirs.staging, tier: "TIER0_LOCAL_STAGING", readOnly: false },
      { name: "exports", rootPath: dirs.exports, tier: "TIER2_EXPORTS", readOnly: false },
      { name: "projects", rootPath: dirs.projects, tier: "PROJECTS", readOnly: false },
    ],
  };
  const configPath = path.join(dirs.data, "config.yaml");
  const binary = path.join(dirs.bin, "branchdam");
  const env = demoEnv(demoDir, { BRANCHDAM_CONFIG: configPath });
  const url = `http://127.0.0.1:${DEMO_PORT}`;

  let server;
  const stop = async () => {
    if (server && server.exitCode === null) {
      server.kill("SIGTERM");
      await new Promise((r) => server.once("exit", r));
    }
    if (keep) return console.log(`[demo] kept ${demoDir}`);
    rmSync(demoDir, { recursive: true, force: true });
  };

  const api = async (pathname, options = {}) => {
    const res = await fetch(`${url}${pathname}`, {
      ...options,
      headers: { "Content-Type": "application/json", ...DEMO_HEADERS, ...options.headers },
    });
    if (!res.ok) throw new Error(`${options.method ?? "GET"} ${pathname} -> ${res.status} ${await res.text()}`);
    const text = await res.text();
    return text ? JSON.parse(text) : undefined;
  };

  try {
    assertDemo(env, cfg, demoDir, { cwd: dirs.run });
    console.log(`[demo] scratch dir ${demoDir}`);
    writeFileSync(configPath, yaml(cfg));
    buildServer(binary);

    console.log("[demo] rendering synthetic media...");
    const counts = generateMedia(dirs);
    console.log(`[demo] media: ${JSON.stringify(counts)}`);

    server = spawn(binary, ["-config", configPath], {
      cwd: dirs.run,
      env,
      stdio: ["ignore", quiet ? "ignore" : "inherit", "inherit"],
    });
    await waitFor(async () => (await fetch(`${url}/healthz`)).ok, "the server");

    // Scan everything twice: a full scan re-resolves every node, and a parent's
    // own pass doesn't look for children that weren't indexed yet.
    const { locations } = await api("/api/v1/storage-locations").then((b) => ({
      locations: Array.isArray(b) ? b : (b.locations ?? b.items ?? []),
    }));
    const scannable = locations.filter((l) => !String(l.tier).startsWith("TIER0"));
    for (let pass = 0; pass < 2; pass++) {
      for (const loc of scannable) {
        await api("/api/v1/scan", {
          method: "POST",
          body: JSON.stringify({ storageLocationId: loc.id, differential: false }),
        });
        await waitFor(async () => {
          const { jobs } = await api("/api/v1/jobs");
          return jobs.every((j) => j.state !== "RUNNING");
        }, `the ${loc.name} scan`);
      }
    }
    // Let the thumbnail worker catch up before anyone looks.
    await waitFor(async () => {
      const { assets } = await api("/api/v1/assets?limit=500");
      return assets.every((a) => a.thumbState !== "PENDING");
    }, "thumbnails");
    return { demoDir, url, api, stop };
  } catch (err) {
    await stop();
    throw err;
  }
}

const invokedDirectly = process.argv[1] && import.meta.url === `file://${process.argv[1]}`;
if (invokedDirectly) {
  const demo = await startDemo({ keep: process.argv.includes("--keep") });
  console.log(`
[demo] branchDAM demo is up: ${demo.url}
[demo] Forward-auth mode: browsing needs no login. Actions (confirm a link,
[demo] scan, trash) need the proxy headers, e.g. from a header-injecting extension:
[demo]   ${Object.entries(DEMO_HEADERS).map(([k, v]) => `${k}: ${v}`).join("\n[demo]   ")}
[demo] Ctrl-C stops it and deletes all demo data.`);
  const shutdown = async () => {
    await demo.stop();
    process.exit(0);
  };
  process.on("SIGINT", shutdown);
  process.on("SIGTERM", shutdown);
}
