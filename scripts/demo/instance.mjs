#!/usr/bin/env node
import { execFileSync, spawn } from "node:child_process";
import { existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { assertDemo, assertPortsFree, demoEnv } from "./env.mjs";
import { generateMedia } from "./media.mjs";
import { webDistStaleReason } from "./webdist.mjs";

/**
 * A throwaway branchDAM with synthetic media and a populated version graph.
 *
 *   make demo          # serve it until Ctrl-C, then delete everything
 *   make screenshots   # scripts/demo/capture.mjs drives startDemo()
 *
 * Everything lives in one mkdtemp directory: a config written from scratch
 * (the checkout's config.yaml is never read), the SQLite database, thumbnails
 * and storage roots. The server binds 127.0.0.1 on a port that must be free,
 * has Immich and metadata write-back off, and runs with an environment built
 * from scratch; scripts/demo/env.mjs refuses anything that points elsewhere.
 * Auth is forward mode: the demo browser sends the X-Authentik-* headers.
 */

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const DEMO_PORT = process.env.DEMO_PORT ?? "3975";

/** What the demo browser and scripts send in place of an auth proxy. */
export const DEMO_HEADERS = {
  "X-Authentik-Username": "demo",
  "X-Authentik-Email": "demo@example.com",
  "X-Authentik-Groups": "branchdam-admins",
};

/**
 * Renders the server config. Every path is emitted as a double-quoted scalar
 * (JSON strings are valid YAML), so a TMPDIR or root path holding ": " or " #"
 * can't change what the server reads; the guard validates `cfg`, and this keeps
 * the file saying the same thing.
 */
export function renderConfig(cfg) {
  const q = (v) => JSON.stringify(String(v));
  const locations = cfg.storageLocations
    .map(
      (l) =>
        `  - name: ${q(l.name)}\n    rootPath: ${q(l.rootPath)}\n    tier: ${q(l.tier)}\n    readOnly: ${l.readOnly === true}`,
    )
    .join("\n");
  return `# Generated by scripts/demo/instance.mjs for a throwaway demo instance.
listenAddr: ${q(cfg.listenAddr)}
logLevel: warn
database:
  path: ${q(cfg.database.path)}
thumbnails:
  enabled: true
  cacheDir: ${q(cfg.thumbnails.cacheDir)}
auth:
  mode: ${q(cfg.auth.mode)}
authz:
  groups:
    - branchdam-admins
immich:
  apiUrl: ""
  apiKey: ""
  libraryId: ""
  exportPath: ${q(cfg.immich.exportPath)}
metadata:
  autoInherit: ${cfg.metadata.autoInherit === true}
trash:
  retentionDays: 0
storageLocations:
${locations}
`;
}

/** The asset list, whichever wrapper the API uses (capture.mjs relies on this too). */
export const assetsOf = (body) => (Array.isArray(body) ? body : (body?.assets ?? body?.items ?? []));

/** True once a child has exited, by exit code or by signal (then exitCode stays null). */
export const hasExited = (child) => child.exitCode !== null || child.signalCode !== null;

/**
 * Stops a child and waits for it. Returns at once for a child that never
 * started (spawn error: no pid) or already exited, whose "exit" event has
 * already fired and would never fire again.
 */
export async function stopChild(child, graceMs = 10_000) {
  if (!child || child.pid === undefined || hasExited(child)) return;
  const exited = new Promise((r) => child.once("exit", r));
  child.kill("SIGTERM");
  const timer = setTimeout(() => !hasExited(child) && child.kill("SIGKILL"), graceMs);
  await exited;
  clearTimeout(timer);
}

export async function waitFor(check, what, timeoutMs = 300_000, { fail } = {}) {
  const deadline = Date.now() + timeoutMs;
  let last;
  while (Date.now() < deadline) {
    // A fatal condition (the server died, or never started) ends the wait at once.
    const fatal = fail?.();
    if (fatal) throw fatal;
    try {
      if (await check()) return;
    } catch (err) {
      last = err;
    }
    await new Promise((r) => setTimeout(r, 500));
  }
  throw new Error(`timed out waiting for ${what}${last ? `: ${last}` : ""}`);
}

/**
 * Runs `start` until it stops failing with HTTP 409. POST /api/v1/scan answers
 * 409 while a scan is still running for that location (ErrScanAlreadyRunning),
 * which a slow runner can hit even after the jobs list looked idle.
 */
export async function retryOnConflict(start, { attempts = 30, delayMs = 2000 } = {}) {
  for (let attempt = 1; ; attempt++) {
    try {
      return await start();
    } catch (err) {
      if (err.status !== 409 || attempt >= attempts) throw err;
      await new Promise((r) => setTimeout(r, delayMs));
    }
  }
}

/**
 * Rebuilds web/dist (embedded into the binary) when it is missing or stale,
 * so a capture never ships an SPA older than the checkout, then builds the
 * server binary.
 */
function buildServer(binary) {
  const stale = webDistStaleReason(path.join(ROOT, "web"));
  if (stale) {
    console.log(`[demo] building the web app (${stale})...`);
    execFileSync("npm", ["--prefix", path.join(ROOT, "web"), "run", "build"], { stdio: "inherit" });
    rmSync(path.join(ROOT, "web/dist/.branchdam-stale"), { force: true });
  }
  console.log("[demo] building the server...");
  execFileSync("go", ["build", "-o", binary, "./cmd/branchdam"], { cwd: ROOT, stdio: "inherit" });
}

export async function startDemo({ keep = false, quiet = false } = {}) {
  await assertPortsFree([DEMO_PORT]);
  // A fixed path, so asset paths in captures read cleanly and identically on
  // every run. Created exclusively: mkdir(2) is atomic, so of two demos started
  // at once exactly one gets EEXIST, and a leftover is refused too.
  const demoDir = path.join(tmpdir(), "branchdam-demo");
  try {
    mkdirSync(demoDir);
  } catch (err) {
    if (err.code === "EEXIST")
      throw new Error(`${demoDir} exists: another demo is running, or remove the leftover`);
    throw err;
  }
  const dirs = Object.fromEntries(
    ["home", "tmp", "run", "bin", "data", "archive", "exports", "projects", "staging"].map((d) => [
      d,
      path.join(demoDir, d),
    ]),
  );
  for (const dir of Object.values(dirs)) mkdirSync(dir, { recursive: true });

  const cfg = {
    listenAddr: `127.0.0.1:${DEMO_PORT}`,
    database: { path: path.join(dirs.data, "branchdam.db") },
    thumbnails: { cacheDir: path.join(dirs.data, "thumbs") },
    auth: { mode: "forward" },
    immich: { apiUrl: "", exportPath: path.join(dirs.exports, "immich") },
    metadata: { autoInherit: false },
    storageLocations: [
      { name: "archive", rootPath: dirs.archive, tier: "TIER3_MASTER_ARCHIVE", readOnly: true },
      { name: "staging", rootPath: dirs.staging, tier: "TIER0_LOCAL_STAGING", readOnly: false },
      { name: "exports", rootPath: dirs.exports, tier: "TIER2_EXPORTS", readOnly: false },
      { name: "projects", rootPath: dirs.projects, tier: "PROJECTS", readOnly: false },
    ],
  };
  const configPath = path.join(dirs.data, "config.yaml");
  const binary = path.join(dirs.bin, "branchdam");
  const env = demoEnv(demoDir, { BRANCHDAM_CONFIG: configPath });
  const url = `http://127.0.0.1:${DEMO_PORT}`;

  let server;
  let serverFailure;
  const stop = async () => {
    await stopChild(server);
    if (keep) return console.log(`[demo] kept ${demoDir}`);
    rmSync(demoDir, { recursive: true, force: true });
  };

  const api = async (pathname, options = {}) => {
    const res = await fetch(`${url}${pathname}`, {
      ...options,
      headers: { "Content-Type": "application/json", ...DEMO_HEADERS, ...options.headers },
    });
    if (!res.ok) {
      const err = new Error(`${options.method ?? "GET"} ${pathname} -> ${res.status} ${await res.text()}`);
      err.status = res.status;
      throw err;
    }
    const text = await res.text();
    return text ? JSON.parse(text) : undefined;
  };

  try {
    assertDemo(env, cfg, demoDir, { cwd: dirs.run });
    console.log(`[demo] scratch dir ${demoDir}`);
    writeFileSync(configPath, renderConfig(cfg));
    buildServer(binary);

    console.log("[demo] rendering synthetic media...");
    const counts = generateMedia(dirs);
    console.log(`[demo] media: ${JSON.stringify(counts)}`);

    server = spawn(binary, ["-config", configPath], {
      cwd: dirs.run,
      env,
      stdio: ["ignore", quiet ? "ignore" : "inherit", "inherit"],
    });
    // Without a listener a failed spawn (ENOENT, EACCES on a noexec TMPDIR) is
    // an uncaught 'error' event that bypasses the catch below and its cleanup.
    server.once("error", (err) => (serverFailure = new Error(`the server failed to start: ${err.message}`)));
    server.once("exit", (code, signal) => {
      serverFailure ??= new Error(`the server exited (${signal ?? `code ${code}`})`);
    });
    const serverAlive = { fail: () => serverFailure };
    await waitFor(async () => (await fetch(`${url}/healthz`)).ok, "the server", undefined, serverAlive);

    // Scan everything twice: a full scan re-resolves every node, and a parent's
    // own pass doesn't look for children that weren't indexed yet.
    const { locations } = await api("/api/v1/storage-locations").then((b) => ({
      locations: Array.isArray(b) ? b : (b.locations ?? b.items ?? []),
    }));
    const scannable = locations.filter((l) => !String(l.tier).startsWith("TIER0"));
    const idle = async () => (await api("/api/v1/jobs")).jobs.every((j) => j.state !== "RUNNING");
    for (let pass = 0; pass < 2; pass++) {
      for (const loc of scannable) {
        await waitFor(idle, `idle jobs before the ${loc.name} scan`, undefined, serverAlive);
        await retryOnConflict(() =>
          api("/api/v1/scan", {
            method: "POST",
            body: JSON.stringify({ storageLocationId: loc.id, differential: false }),
          }),
        );
        await waitFor(idle, `the ${loc.name} scan`, undefined, serverAlive);
      }
    }
    // Let the thumbnail worker catch up before anyone looks.
    await waitFor(
      async () => assetsOf(await api("/api/v1/assets?limit=500")).every((a) => a.thumbState !== "PENDING"),
      "thumbnails",
      undefined,
      serverAlive,
    );
    return { demoDir, url, api, stop };
  } catch (err) {
    await stop();
    throw err;
  }
}

// pathToFileURL percent-encodes like import.meta.url (paths with spaces, non-ASCII).
const invokedDirectly = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (invokedDirectly) {
  const demo = await startDemo({ keep: process.argv.includes("--keep") });
  console.log(`
[demo] branchDAM demo is up: ${demo.url}
[demo] Forward-auth mode: browsing needs no login. Actions (confirm a link,
[demo] scan, trash) need the proxy headers, e.g. from a header-injecting extension:
[demo]   ${Object.entries(DEMO_HEADERS).map(([k, v]) => `${k}: ${v}`).join("\n[demo]   ")}
[demo] Ctrl-C stops it and deletes all demo data.`);
  const shutdown = async () => {
    await demo.stop();
    process.exit(0);
  };
  process.on("SIGINT", shutdown);
  process.on("SIGTERM", shutdown);
}
